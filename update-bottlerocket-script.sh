ARG BUILD_BASE
ARG FINAL_BASE=${BUILD_BASE}

# ---------- build stage: install AWS CLI v2 + tuftool ----------
FROM ${BUILD_BASE} AS build
ENV AWS_PAGER=""

# AWS CLI v2 from the zip supplied in the build context (no network needed).
# vendor/ holds awscli-exe-linux-aarch64.zip and/or awscli-exe-linux-x86_64.zip.
COPY vendor/ /tmp/vendor/
RUN set -eux; \
    zip="/tmp/vendor/awscli-exe-linux-$(uname -m).zip"; \
    test -f "$zip"; \
    if command -v unzip >/dev/null 2>&1; then \
        unzip -q "$zip" -d /tmp; \
    else \
        python3 -c "import zipfile,sys; zipfile.ZipFile(sys.argv[1]).extractall('/tmp')" "$zip"; \
        chmod -R u+x /tmp/aws/install /tmp/aws/dist; \
    fi; \
    /tmp/aws/install --install-dir /opt/aws-cli --bin-dir /opt/aws-bin; \
    rm -rf /tmp/aws /tmp/vendor

# Cargo -> CodeArtifact (config generated by build.sh; contains no token)
COPY config.toml /usr/local/cargo/config.toml

# tuftool via CodeArtifact. Token comes from a build secret (raw token, no "Bearer ").
# The registry cache is cleared first: a stale index previously caused a false
# "failed to select a version for snafu" resolution error.
RUN --mount=type=secret,id=ca_token \
    set -eu; \
    rm -rf /usr/local/cargo/registry/index /usr/local/cargo/registry/cache; \
    export CARGO_REGISTRIES_CODEARTIFACT_TOKEN="$(cat /run/secrets/ca_token)"; \
    cargo install tuftool --locked --root /opt/tuftool

# ---------- final stage: glibc image, binaries only ----------
FROM ${FINAL_BASE}
ENV AWS_PAGER=""
COPY --from=build /opt/aws-cli /opt/aws-cli
COPY --from=build /opt/tuftool/bin/tuftool /usr/local/bin/tuftool
RUN ln -s /opt/aws-cli/v2/current/bin/aws /usr/local/bin/aws \
 && aws --version \
 && tuftool --version
